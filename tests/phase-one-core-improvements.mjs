import assert from "node:assert/strict";
process.env.HUAMEI_LLM_ENABLED = "false";
process.env.HUAMEI_GRAPHRAG_ENABLED = "false";
for (const name of ["ACQUISITION_SESSION", "ACQUISITION_OPERATIONS", "KNOWLEDGE_RELEASE", "KNOWLEDGE_INGESTION_ADMISSION", "CONVERSATION_FEEDBACK"]) process.env[`HUAMEI_${name}_STORE_FILE`] = ":memory:";
process.env.HUAMEI_RUNTIME_KNOWLEDGE_INDEX_FILE = ":memory:";
const { processAcquisitionEnvelope } = await import("../server/acquisition-domain-service.mjs");
const { normalizeChannelInbound } = await import("../server/acquisition-channel-adapters.mjs");
const { inspectRisk } = await import("../server/agent-runtime.mjs");
const { ensureHandoverTask, claimHandover, listHandovers } = await import("../server/acquisition-operations-store.mjs");
const { buildChoicePrompt, resolvePendingChoice, resolveBreastMethodCorrection } = await import("../server/acquisition-choice-slots.mjs");
const tenant = "huamei-shanghai";
let counter = 0;
const envelope = (text, id = "p0-correction") => normalizeChannelInbound("web", { tenant_id:tenant, session_id:id, message:text, message_id:`p0-${++counter}` });
const turn = (text, id) => processAcquisitionEnvelope(envelope(text, id));
const greeting = await turn("你好", "p0-greeting");
assert.match(greeting.reply.text, /AI获客顾问小美/);
assert.doesNotMatch(greeting.reply.text, /安安|网约车|会员权益|预算|手机号/);
const processInfo = await turn("第二个", "p0-greeting");
assert.match(processInfo.reply.text, /面诊一般/);
assert.doesNotMatch(processInfo.reply.text, /地址|停车/);
await turn("我想了解假体隆胸");
const correction = await turn("不是假体，是脂肪");
assert.equal(correction.profile_signals.known_slots.breast_method, "autologous_fat");
assert.match(correction.reply.text, /自体脂肪(?:丰胸|隆胸)/);
assert.doesNotMatch(correction.reply.text, /主要想改善哪个部位|假体形态/);
const continued = await turn("恢复呢");
assert.match(continued.reply.text, /自体脂肪(?:丰胸|隆胸)/);
assert.equal(continued.profile_signals.known_slots.breast_method, "autologous_fat");
const reversed = await turn("改成假体丰胸");
assert.equal(reversed.profile_signals.known_slots.breast_method, "implant");
const switched = await turn("隆鼻术是什么");
assert.match(switched.reply.text, /隆鼻术.*是指/);
assert.doesNotMatch(switched.reply.text, /假体丰胸|自体脂肪丰胸|面部轮廓/);
assert.deepEqual(switched.reply.citations.map((item) => item.source_record_id), ["KB-P-033"]);
const nasalFollowup = await turn("恢复呢");
assert.doesNotMatch(nasalFollowup.reply.text, /假体丰胸|自体脂肪(?:丰胸|隆胸)/);
const comparison = await turn("假体隆鼻和鼻综合区别", "p0-comparison");
assert.deepEqual(comparison.reply.citations.map((item) => item.source_record_id), ["KB-P-031", "KB-P-026"]);
assert.match(comparison.reply.text, /假体隆鼻和鼻综合/);
const doctor = await turn("李健院长有哪些项目", "p0-doctor");
assert.equal(doctor.status, "handover_required");
assert.match(doctor.reply.text, /未取得.*已发布关系依据/);
assert.ok(doctor.handover.id);
const doctorTask = (await listHandovers({ tenant_id:tenant })).find((item) => item.id === doctor.handover.id);
assert.deepEqual(doctorTask.doctors, ["李健"]);
assert.equal(doctorTask.known_slots.preferred_doctor, "李健");
assert.match(doctorTask.slot_sources.preferred_doctor.message_id, /^p0-/);
assert.ok(Array.isArray(doctorTask.pending_fields));
const choice = buildChoicePrompt("breast_method");
assert.equal(resolvePendingChoice("不是第二种", choice).selection, null);
assert.equal(resolvePendingChoice("不是第二种，是第一种", choice).selection.value, "implant");
assert.equal(resolveBreastMethodCorrection("不是假体，是面部脂肪填充", { known_projects:["胸部整形"] }), null);
assert.equal(resolveBreastMethodCorrection("改成脂肪", {}), null);
for (const text of ["我要人工服务", "找真人客服", "转接人工", "不要机器人"]) assert.equal(inspectRisk(text).decision, "handover", text);
for (const text of ["不需要人工服务", "不用转人工", "暂不找真人客服"]) assert.equal(inspectRisk(text).decision, "allow", text);
assert.equal(inspectRisk("需要人工顾问核实", { includeHumanRequests:false }).decision, "allow", "An assistant suggestion is not customer consent to handover");
const requested = await turn("我要人工服务", "p0-human");
assert.equal(requested.status, "handover_required");
assert.ok(requested.handover.id);
await turn("找真人客服", "p0-human");
assert.equal((await listHandovers({ tenant_id:tenant })).filter((item) => item.conversation_id === "p0-human").length, 1);
await claimHandover(requested.handover.id, { tenant_id:tenant, assignee:"p0-advisor" });
const silent = await turn("请继续回答", "p0-human");
assert.equal(silent.reply.text, "");
assert.equal(silent.delivery.suppress_ai, true);

// Hold a real runtime invocation at the provider boundary, claim the same
// conversation, then release generation. No external provider is contacted.
let release, entered;
const gate = new Promise((resolve) => { release = resolve; });
const started = new Promise((resolve) => { entered = resolve; });
const originalFetch = globalThis.fetch;
process.env.HUAMEI_LLM_ENABLED = "true";
process.env.HUAMEI_LLM_BASE_URL = "https://local-fixture.invalid/v1";
process.env.HUAMEI_LLM_API_KEY = "test-only-key";
process.env.HUAMEI_LLM_MODEL = "fixture";
process.env.HUAMEI_LLM_MAX_RETRIES = "0";
globalThis.fetch = async (url) => {
  assert.match(String(url), /^https:\/\/local-fixture\.invalid\//);
  entered(); await gate;
  return new Response(JSON.stringify({ choices:[{ message:{ content:JSON.stringify({ status:"completed", message:"测试模型回复" }) } }] }), { status:200 });
};
const input = envelope("介绍光子嫩肤", "p0-inflight");
let timeout;
try {
  const pending = processAcquisitionEnvelope(input);
  await Promise.race([started, new Promise((_, reject) => { timeout = setTimeout(() => reject(new Error("Runtime did not reach provider fixture")), 5000); })]);
  clearTimeout(timeout);
  const task = await ensureHandoverTask({ envelope:{ ...input, message:{ id:"p0-inflight-human", text:"转人工" } }, result:{ status:"handover_required", handover:{ required:true, reason:"human_request" } } });
  await claimHandover(task.id, { tenant_id:tenant, assignee:"p0-advisor" });
  release();
  const result = await pending;
  assert.equal(result.status, "human_active");
  assert.equal(result.reply.text, "");
  assert.deepEqual(result.reply.citations, []);
  assert.equal(result.delivery.suppress_ai, true);
} finally { clearTimeout(timeout); release(); globalThis.fetch = originalFetch; process.env.HUAMEI_LLM_ENABLED = "false"; }
console.log("✓ P0 固定身份、编号入口、纠正连续性、否定选择、人工请求与生成中接管通过");
