import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
if (process.env.HUAMEI_PERSISTENCE_BACKEND !== "postgres") throw new Error("Real PostgreSQL required");
process.env.HUAMEI_RUNTIME_ENV = "development";
process.env.HUAMEI_MEMBER_CHECK_ENABLED = "false";
process.env.HUAMEI_IDENTITY_PEPPER = randomBytes(32).toString("hex");
process.env.HUAMEI_CONTACT_VAULT_KEYRING_JSON = JSON.stringify({ active_key_id:"apt-contact-v1", keys:{ "apt-contact-v1":randomBytes(32).toString("base64") } });
process.env.HUAMEI_FIELD_ENCRYPTION_KEYRING_JSON = JSON.stringify({ active_key_id:"apt-v1", keys:{ "apt-v1":randomBytes(32).toString("base64") } });
const { createPostgresClient, getPostgresClient, closePostgresClient } = await import("../server/platform/postgres.mjs");
const { createAppointmentIntake:create, changeCustomerAppointment:change, listAppointmentIntakes:list, claimAppointmentIntake:claim } = await import("../server/appointment-intake-store.mjs");
const { appointmentStateTransaction:transaction } = await import("../server/persistence/appointment-state-store.mjs");
const { upsertAcquisitionLead, getCapturedLeadReferenceForSession } = await import("../server/lead-store.mjs");
const { revealContactForClaimedAppointment:reveal } = await import("../server/contact-vault.mjs");
const tenant = `apt-${randomUUID().slice(0,8)}`;
const other = `apt-${randomUUID().slice(0,8)}`;
const migrator = createPostgresClient({ connectionString:process.env.HUAMEI_MIGRATION_DATABASE_URL });
const base = { tenant_id:tenant, conversation_id:"pg-registration-session", channel:"web", source_action_id:"act_0123456789abcdef01234567", customer_confirmed:true, projects:["测试项目"], branch:"测试院区", internal_customer_reference:"private-appointment-ref", preferred_date:new Date(Date.now()+86400000*5).toISOString().slice(0,10), time_period:"afternoon" };
try {
 await migrator.transaction(async (c) => { await c.query("SET LOCAL ROLE huamei_owner"); await c.query("INSERT INTO tenants(tenant_id,display_name) VALUES($1,$1),($2,$2)",[tenant,other]); });
 await getPostgresClient().tenantQuery(tenant,"INSERT INTO conversation_sessions(tenant_id,session_id,channel,external_conversation_id,state) VALUES($1,'internal-arrival-session','web',$2,'{}'::jsonb)",[tenant,base.conversation_id]);
 await upsertAcquisitionLead({ tenant_id:tenant, session_id:base.conversation_id, mobile:"13876543210", service_consent:true });
 const captured = await getCapturedLeadReferenceForSession({ tenant_id:tenant, session_id:base.conversation_id });
 assert.equal(captured.phone_verification_status,"pending_manual");
 base.internal_customer_reference = captured.customer_reference;
 const results = await Promise.all(Array.from({length:20}, () => create(base)));
 assert.equal(results.filter((r) => !r.replayed).length, 1);
 assert.equal(new Set(results.map((r) => r.intake.id)).size, 1);
 const item = results[0].intake;
 let state = await transaction(base, (s)=>s);
 assert.equal(state.registrations.length,1); assert.equal(state.events.length,1); assert.equal(state.followups.length,1); assert.equal(state.notices.length,1);
 const raw = await getPostgresClient().tenantQuery(tenant,"SELECT payload::text AS value FROM appointment_sessions WHERE tenant_id=$1",[tenant]);
 assert.doesNotMatch(raw.rows[0].value, /private-appointment-ref|测试项目|测试院区/);
 const foreign = await getPostgresClient().tenantQuery(other,"SELECT payload FROM appointment_sessions WHERE tenant_id=$1",[tenant]);
 assert.equal(foreign.rowCount,0);
 const before = JSON.stringify(state);
 await assert.rejects(transaction(base, (s) => { s.registrations.length=0; throw new Error("injected rollback"); }), /injected rollback/);
 assert.equal(JSON.stringify(await transaction(base,(s)=>s)),before);
 const versionRace = await Promise.allSettled([6,7].map((days) => change({ ...base, appointment_intake_id:item.id, action:"reschedule", expected_version:1, preferred_date:new Date(Date.now()+86400000*days).toISOString().slice(0,10), idempotency_key:`pg-change-${days}` })));
 assert.equal(versionRace.filter((r)=>r.status==="fulfilled").length,1);
 assert.equal(versionRace.find((r)=>r.status==="rejected").reason.code,"APPOINTMENT_VERSION_CONFLICT");
 await closePostgresClient();
 assert.equal((await list({ tenant_id:tenant }))[0].version,2,"new connection restores durable data");
 state = await transaction(base,(s)=>s);
 assert.equal(state.followups.length,1);
 assert.equal(state.notices.filter((n)=>n.status==="manual_required").length,1);
 const audit = await getPostgresClient().tenantQuery(tenant,"SELECT action FROM audit_events WHERE tenant_id=$1 AND resource_type='appointment_registration'",[tenant]);
 assert.equal(audit.rowCount,2,"exactly one audit event per committed version");
 const contactInput = { tenantId:tenant, appointmentId:item.id, actor:"sales-a", revealRequestId:"apt-contact-reveal-1" };
 await assert.rejects(reveal(contactInput), { code:"CONTACT_REVEAL_HANDOVER_NOT_CLAIMED" });
 await claim({ tenant_id:tenant, appointment_intake_id:item.id, actor:"sales-a" });
 await assert.rejects(reveal({ ...contactInput, actor:"sales-b", revealRequestId:"apt-contact-other" }), { code:"CONTACT_REVEAL_ASSIGNEE_MISMATCH" });
 const disclosed = await reveal({ ...contactInput, revealRequestId:"apt-contact-reveal-2" });
 assert.equal(disclosed.value,"13876543210");
 assert.equal(disclosed.browser_storage_allowed,false);
 await assert.rejects(reveal({ ...contactInput, revealRequestId:"apt-contact-reveal-2" }), { code:"CONTACT_REVEAL_REPLAYED" });
 await migrator.transaction(async(c)=>{ await c.query("SET LOCAL ROLE huamei_owner"); await c.query("UPDATE consents SET granted=false WHERE tenant_id=$1 AND consent_type='service' AND is_current",[tenant]); });
 assert.equal(await getCapturedLeadReferenceForSession({ tenant_id:tenant, session_id:base.conversation_id }),null);
 await assert.rejects(reveal({ ...contactInput, revealRequestId:"apt-contact-withdrawn" }), { code:"CONTACT_REVEAL_SERVICE_CONSENT_REQUIRED" });
 await change({ ...base, appointment_intake_id:item.id, action:"cancel", expected_version:2, idempotency_key:"pg-appointment-cancel" });
 await assert.rejects(reveal({ ...contactInput, revealRequestId:"apt-contact-cancelled" }), { code:"CONTACT_REVEAL_HANDOVER_NOT_CLAIMED" });
 console.log("✓ PostgreSQL到院登记20路并发、原子保存、失败回滚、改期版本竞争、密文RLS及重连恢复通过");
} finally {
 await closePostgresClient();
 await migrator.transaction(async(c)=>{ await c.query("SET LOCAL ROLE huamei_owner"); await c.query("DELETE FROM appointment_sessions WHERE tenant_id=ANY($1::text[])",[[tenant,other]]); });
 await migrator.close();
}
