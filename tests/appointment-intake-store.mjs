import assert from "node:assert/strict";
process.env.HUAMEI_APPOINTMENT_REGISTRATION_FILE = ":memory:";
const { createAppointmentIntake:create, changeCustomerAppointment:change, claimAppointmentIntake:claim, resolveAppointmentIntake:resolve, listAppointmentIntakes:list, getAppointmentIntake:get, createInternalScheduleSlot } = await import("../server/appointment-intake-store.mjs");
const { appointmentStateTransaction:transaction } = await import("../server/persistence/appointment-state-store.mjs");
const date = (n) => new Date(Date.now() + n * 86400000).toISOString().slice(0,10);
const base = { tenant_id:"huamei-shanghai", channel:"web", conversation_id:"appointment-unit", internal_customer_reference:"private-test-reference", source_action_id:"act_0123456789abcdef01234567", projects:["双眼皮"], branch:"上海华美医疗美容医院", preferred_date:date(5), time_period:"afternoon", customer_confirmed:true };
await assert.rejects(create({ ...base, internal_customer_reference:null }), { code:"APPOINTMENT_CONTACT_REQUIRED" });
await assert.rejects(create({ ...base, customer_confirmed:false }), { code:"APPOINTMENT_CONFIRMATION_REQUIRED" });
await assert.rejects(create({ ...base, preferred_date:"本周六" }), { code:"APPOINTMENT_DATE_REQUIRED" });
await assert.rejects(create({ ...base, branch:"" }), { code:"APPOINTMENT_BRANCH_REQUIRED" });
const first = await create(base);
assert.equal(first.intake.status, "registered");
assert.equal(first.intake.contact_status, "pending_manual");
assert.match(first.intake.appointment_no, /^HM[A-F0-9]{32}$/);
assert.doesNotMatch(JSON.stringify(first), /private-test-reference|confirmation/);
const race = await Promise.all(Array.from({length:20}, () => create(base)));
assert.ok(race.every((x) => x.replayed && x.intake.id === first.intake.id));
await assert.rejects(create({ ...base, preferred_date:date(6) }), { code:"APPOINTMENT_IDEMPOTENCY_CONFLICT" });
await assert.rejects(create({ ...base, source_action_id:"act_1123456789abcdef01234567" }), { code:"APPOINTMENT_ACTIVE_EXISTS" });
const scope = { ...base, appointment_intake_id:first.intake.id };
assert.equal(await get({ tenant_id:"other-tenant", appointment_intake_id:first.intake.id }), null);
await claim({ ...scope, actor:"sales-a" });
await assert.rejects(claim({ ...scope, actor:"sales-b" }), { code:"APPOINTMENT_ALREADY_CLAIMED" });
assert.equal((await list({tenant_id:base.tenant_id, assigned_only:true, actor:"sales-b"})).length, 0);
await assert.rejects(resolve({ ...scope, actor:"sales-b", status:"completed", note:"测试", idempotency_key:"resolve-other" }), { code:"APPOINTMENT_ASSIGNEE_MISMATCH" });
await assert.rejects(resolve({ ...scope, actor:"sales-a", status:"confirmed", note:"测试", idempotency_key:"resolve-invalid" }), { code:"APPOINTMENT_STATUS_INVALID" });
const done = await resolve({ ...scope, actor:"sales-a", status:"completed", note:"已回电沟通", idempotency_key:"resolve-first" });
assert.equal(done.intake.status, "registered");
assert.equal(done.intake.followup_status, "completed");
const changeRequest = { ...scope, action:"reschedule", expected_version:1, preferred_date:date(8), time_period:"", idempotency_key:"customer-change" };
const rescheduled = await change(changeRequest);
assert.equal(rescheduled.intake.version, 2);
assert.equal(rescheduled.intake.time_precision, "date");
assert.equal(rescheduled.intake.followup_status, "claimed");
assert.equal((await change(changeRequest)).replayed, true);
await assert.rejects(change({ ...changeRequest, idempotency_key:"stale-change" }), { code:"APPOINTMENT_VERSION_CONFLICT" });
assert.equal(await change({ ...changeRequest, conversation_id:"someone-else", expected_version:2 }), null);
const cancelled = await change({ ...scope, action:"cancel", expected_version:2, idempotency_key:"customer-cancel" });
assert.equal(cancelled.intake.version, 3);
assert.equal(cancelled.intake.status, "cancelled");
const state = await transaction(base, (value) => value);
assert.equal(state.registrations.length, 1);
assert.equal(state.followups.length, 1);
assert.equal(state.followups[0].status, "cancelled");
assert.equal(state.notices.filter((n) => n.status === "manual_required").length, 1);
assert.ok(state.notices.slice(0,-1).every((n) => n.status === "cancelled"));
const before = JSON.stringify(state);
await assert.rejects(transaction(base, (value) => { value.registrations.length = 0; throw new Error("save failed"); }), /save failed/);
assert.equal(JSON.stringify(await transaction(base, (value) => value)), before);
assert.throws(() => createInternalScheduleSlot({}), { code:"SCHEDULE_NOT_IN_PHASE_ONE" });
process.env.HUAMEI_RUNTIME_ENV = "production";
await assert.rejects(list({ tenant_id:base.tenant_id }), { code:"APPOINTMENT_PERSISTENCE_REQUIRED" });
console.log("✓ 到院登记确认、幂等、领取权限、改期取消、版本冲突、事务回滚与生产持久化门禁通过");
